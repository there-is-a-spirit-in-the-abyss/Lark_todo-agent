test('actual pointer dragging moves entire subtree into staging then onto another owner task',async({page})=>{
  await page.getByRole('button',{name:'适应全部任务'}).click();
  await page.waitForTimeout(400);
  const source=await page.locator('[data-task-id="api"] .task-title').boundingBox();
  const stage=await page.getByTestId('staging-zone').boundingBox();
  await page.mouse.move(source.x+80,source.y+8);
  await page.mouse.down();
  await page.mouse.move(stage.x+75,stage.y+90,{steps:30});
  await page.mouse.up();
  await expect.poll(async()=>((await persisted(page))?.tasks.find(t=>t.id==='api').parent)).toBeNull();
  let s=await persisted(page);
  expect(s.tasks.find(t=>t.id==='auth').parent).toEqual({kind:'task',id:'api'});
  expect(s.tasks.find(t=>t.id==='integration').parent).toEqual({kind:'task',id:'auth'});
  await page.getByRole('button',{name:'适应全部任务'}).click();
  await page.waitForTimeout(400);
  const src=await page.locator('[data-task-id="api"] .task-title').boundingBox();
  const dst=await page.locator('[data-task-id="page"]').boundingBox();
  await page.mouse.move(src.x+50,src.y+8);await page.mouse.down();
  await page.mouse.move(dst.x+90,dst.y+40,{steps:30});await page.mouse.up();
  await expect.poll(async()=>((await persisted(page))?.tasks.find(t=>t.id==='api').parent)).toEqual({kind:'task',id:'page'});
});
