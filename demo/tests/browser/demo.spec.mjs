test('mobile touch drag stages a whole branch and mobile dialog reattaches it',async({browser})=>{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
  const page=await context.newPage();await page.goto('/');
  await expect(page.locator('[data-task-id="api"]')).toBeVisible();
  await page.waitForTimeout(300);
  const source=await page.locator('[data-task-id="api"] .task-title').boundingBox();
  const stage=await page.getByTestId('staging-zone').boundingBox();
  const session=await context.newCDPSession(page);
  const start={x:source.x+source.width/2,y:source.y+source.height/2};
  const end={x:Math.max(20,stage.x+25),y:stage.y+70};
  await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[start]});
  for(let i=1;i<=20;i++)await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:start.x+(end.x-start.x)*i/20,y:start.y+(end.y-start.y)*i/20}]});
  await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await expect.poll(async()=>((await persisted(page))?.tasks.find(t=>t.id==='api').parent)).toBeNull();
  await page.locator('[data-task-id="api"] .task-title').tap();
  await page.getByRole('button',{name:'移动分支',exact:true}).tap();
  await page.getByLabel('接入位置').selectOption('project:p-brand');
  await page.getByRole('button',{name:'确认移动'}).tap();
  expect((await persisted(page)).tasks.find(t=>t.id==='api').parent).toEqual({kind:'project',id:'p-brand'});
  await context.close();
});
